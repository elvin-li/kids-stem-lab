function replaceSection(t, id, neu) {
  const re = new RegExp(`<section\\b[^>]*aria-labelledby="${id}"[^>]*>[\\s\\S]*?<\\/section>`, "m");
  if (!re.test(t)) throw new Error("MISS " + id);
  return t.replace(re, neu);
}
